-- =============================================================================
-- Captação de imóveis (modo imobiliária): oportunidades com proprietário em
-- potencial, imóvel preliminar, avaliação e comparativos, proposta de
-- administração/intermediação, exclusividade, autorização de anúncio,
-- checklist de documentos, histórico e conversão em imóvel ativo.
-- =============================================================================

create table if not exists public.captacoes (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  numero bigint generated by default as identity,
  status text not null default 'prospeccao'
    check (status in ('prospeccao','contato','avaliacao','proposta','autorizacao','captado','nao_captado')),
  etapa_max int not null default 0,
  origem text not null default 'outro',
  corretor_id uuid references public.pessoas(id) on delete set null,
  lead_id uuid references public.leads(id) on delete set null,
  -- Proprietário em potencial
  proprietario_id uuid references public.pessoas(id) on delete set null,
  proprietario_nome text not null,
  proprietario_telefone text,
  proprietario_email text,
  -- Imóvel preliminar
  tipo text not null default 'apartamento',
  finalidades text[] not null default '{locacao}',
  cep text, logradouro text, numero_end text, complemento text, bairro text, cidade text, uf text,
  area numeric(10,2),
  quartos int, suites int, banheiros int, vagas int,
  valor_pretendido numeric(14,2),
  observacoes text,
  -- Avaliação
  valor_avaliado_aluguel numeric(14,2),
  valor_avaliado_venda numeric(14,2),
  avaliado_em date,
  avaliacao_notas text,
  -- Proposta
  proposta_tipo text not null default 'administracao' check (proposta_tipo in ('administracao','intermediacao','ambos')),
  proposta_taxa_adm numeric(6,3),
  proposta_taxa_intermediacao numeric(6,3),
  proposta_comissao_venda numeric(6,3),
  proposta_status text not null default 'rascunho' check (proposta_status in ('rascunho','enviada','aceita','recusada')),
  proposta_enviada_em date,
  proposta_texto text,
  -- Exclusividade e autorização
  exclusivo boolean not null default false,
  exclusividade_inicio date,
  exclusividade_fim date,
  autorizacao_anuncio boolean not null default false,
  autorizacao_data date,
  autorizacao_validade date,
  fotos_status text not null default 'pendente' check (fotos_status in ('pendente','agendadas','feitas','tratadas')),
  -- Documentos
  checklist jsonb not null default '{}'::jsonb,
  -- Resultado
  motivo_nao_captado text,
  nao_captado_em timestamptz,
  imovel_id uuid references public.imoveis(id) on delete set null,
  captado_em date,
  created_at timestamptz not null default now()
);
create index if not exists captacoes_status_idx on public.captacoes (organizacao_id, status);
create index if not exists captacoes_corretor_idx on public.captacoes (corretor_id);

create table if not exists public.captacao_eventos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  captacao_id uuid not null references public.captacoes(id) on delete cascade,
  tipo text not null default 'nota'
    check (tipo in ('entrada','ligacao','whatsapp','email','reuniao','nota','etapa','negociacao','proposta','perda','conversao')),
  descricao text,
  data timestamptz not null default now(),
  usuario_id uuid default auth.uid()
);
create index if not exists captacao_eventos_idx on public.captacao_eventos (captacao_id, data desc);

create table if not exists public.captacao_comparativos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  captacao_id uuid not null references public.captacoes(id) on delete cascade,
  descricao text not null,
  valor numeric(14,2) not null,
  area numeric(10,2),
  finalidade text not null default 'locacao' check (finalidade in ('locacao','venda')),
  fonte text,
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['captacoes','captacao_eventos','captacao_comparativos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create index if not exists %I on public.%I (organizacao_id)', t || '_org_idx', t);
    execute format('drop policy if exists %I on public.%I', t || '_org', t);
    execute format($p$create policy %I on public.%I for all to authenticated
      using (organizacao_id in (select privado.org_ids()))
      with check (organizacao_id in (select privado.org_ids()))$p$, t || '_org', t);
  end loop;
end $$;

-- Visitas também servem para avaliação de captação (e, na agenda, para tipos diversos).
alter table public.visitas add column if not exists captacao_id uuid references public.captacoes(id) on delete set null;
alter table public.visitas add column if not exists tipo text not null default 'visita';

-- Leads antigos do funil "captação" viram oportunidades de captação.
insert into public.captacoes (organizacao_id, origem, corretor_id, lead_id, proprietario_nome, proprietario_telefone, proprietario_email, observacoes, created_at)
select l.organizacao_id, l.origem, l.corretor_id, l.id, l.nome, l.telefone, l.email, l.observacoes, l.created_at
  from public.leads l
 where l.funil = 'captacao'
   and not exists (select 1 from public.captacoes c where c.lead_id = l.id);

/**
 * Converte a captação em imóvel ativo: cria (ou reaproveita) o proprietário,
 * cria o imóvel com os dados preliminares e a avaliação e liga os dois.
 */
create or replace function public.converter_captacao(p_id uuid, p_codigo text)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  c public.captacoes%rowtype;
  v_pessoa uuid;
  v_imovel uuid;
begin
  select * into c from public.captacoes where id = p_id for update;
  if not found then raise exception 'Captação não encontrada.'; end if;
  if c.imovel_id is not null then raise exception 'Esta captação já virou imóvel.'; end if;
  if coalesce(btrim(p_codigo), '') = '' then raise exception 'Informe o código do novo imóvel.'; end if;

  v_pessoa := c.proprietario_id;
  if v_pessoa is null then
    insert into public.pessoas (organizacao_id, nome, telefone, email, papeis)
    values (c.organizacao_id, c.proprietario_nome, c.proprietario_telefone, c.proprietario_email, '{proprietario}')
    returning id into v_pessoa;
  else
    update public.pessoas set papeis = array(select distinct unnest(papeis || '{proprietario}')) where id = v_pessoa;
  end if;

  insert into public.imoveis (organizacao_id, codigo, tipo, finalidades, status, cep, logradouro, numero, complemento, bairro, cidade, uf,
                              area_util, quartos, suites, banheiros, vagas, valor_aluguel, valor_venda, descricao,
                              exclusivo, exclusividade_inicio, exclusividade_fim, autorizacao_data, autorizacao_validade,
                              corretor_id, captado_em)
  values (c.organizacao_id, btrim(p_codigo), c.tipo, c.finalidades, 'disponivel', c.cep, c.logradouro, c.numero_end, c.complemento, c.bairro, c.cidade, c.uf,
          c.area, c.quartos, c.suites, c.banheiros, c.vagas,
          coalesce(c.valor_avaliado_aluguel, case when 'locacao' = any (c.finalidades) then c.valor_pretendido end),
          coalesce(c.valor_avaliado_venda, case when 'venda' = any (c.finalidades) then c.valor_pretendido end),
          c.observacoes, c.exclusivo, c.exclusividade_inicio, c.exclusividade_fim, c.autorizacao_data, c.autorizacao_validade,
          c.corretor_id, current_date)
  returning id into v_imovel;

  insert into public.imovel_proprietarios (organizacao_id, imovel_id, pessoa_id, percentual) values (c.organizacao_id, v_imovel, v_pessoa, 100);

  update public.captacoes
     set status = 'captado', etapa_max = 5, imovel_id = v_imovel, proprietario_id = v_pessoa, captado_em = current_date
   where id = c.id;
  insert into public.captacao_eventos (organizacao_id, captacao_id, tipo, descricao)
  values (c.organizacao_id, c.id, 'conversao', 'Virou o imóvel ' || btrim(p_codigo));
  return v_imovel;
end;
$$;
revoke execute on function public.converter_captacao(uuid, text) from public, anon;
grant execute on function public.converter_captacao(uuid, text) to authenticated;

-- Formulário público: "quero anunciar meu imóvel" cai direto na captação.
create or replace function public.receber_lead(p_token uuid, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  org public.organizacoes%rowtype;
  v_nome text := left(btrim(coalesce(p->>'nome', '')), 120);
  v_tel text := left(btrim(coalesce(p->>'telefone', '')), 40);
  v_email text := lower(left(btrim(coalesce(p->>'email', '')), 160));
  v_msg text := left(btrim(coalesce(p->>'mensagem', '')), 2000);
  v_origem text := lower(coalesce(p->>'origem', 'site'));
  v_funil text := lower(coalesce(p->>'funil', 'locacao'));
  v_dig text := right(regexp_replace(coalesce(p->>'telefone', ''), '\D', '', 'g'), 9);
  v_existente uuid;
  v_id uuid;
  v_corretor uuid;
  v_imovel uuid;
begin
  select * into org from public.organizacoes where leads_token = p_token and modo = 'imobiliaria';
  if not found then raise exception 'Link de captação inválido.'; end if;
  if v_nome = '' then raise exception 'Informe o nome.'; end if;
  if v_tel = '' and v_email = '' then raise exception 'Informe telefone ou e-mail.'; end if;
  if v_origem not in ('site','whatsapp','instagram','facebook','tiktok','portal','zap','vivareal','olx','imovelweb','indicacao','placa','telefone','email','visita','outro') then
    v_origem := 'site';
  end if;
  if v_funil not in ('locacao','venda','captacao') then v_funil := 'locacao'; end if;
  if (select count(*) from public.lead_eventos where organizacao_id = org.id and tipo in ('entrada','mensagem') and data > now() - interval '1 hour')
   + (select count(*) from public.captacao_eventos where organizacao_id = org.id and tipo = 'entrada' and data > now() - interval '1 hour') > 300 then
    raise exception 'Muitas mensagens agora. Tente de novo mais tarde.';
  end if;

  if org.distribuicao_leads = 'rodizio' then
    select pe.id into v_corretor
      from public.pessoas pe
     where pe.organizacao_id = org.id and 'corretor' = any (pe.papeis) and pe.recebe_leads
     order by greatest(
       (select max(l.atribuido_em) from public.leads l where l.corretor_id = pe.id),
       (select max(c.created_at) from public.captacoes c where c.corretor_id = pe.id)) nulls first, pe.nome
     limit 1;
  end if;

  -- Proprietário querendo anunciar: oportunidade de captação.
  if v_funil = 'captacao' then
    select c.id into v_existente
      from public.captacoes c
     where c.organizacao_id = org.id and c.status not in ('captado','nao_captado')
       and ((v_email <> '' and lower(c.proprietario_email) = v_email)
         or (length(v_dig) >= 8 and right(regexp_replace(coalesce(c.proprietario_telefone, ''), '\D', '', 'g'), 9) = v_dig))
     limit 1;
    if v_existente is not null then
      insert into public.captacao_eventos (organizacao_id, captacao_id, tipo, descricao, usuario_id)
      values (org.id, v_existente, 'nota', 'Novo contato (' || v_origem || ')' || coalesce(': ' || nullif(v_msg, ''), ''), null);
      return jsonb_build_object('id', v_existente, 'duplicado', true, 'captacao', true);
    end if;
    insert into public.captacoes (organizacao_id, origem, corretor_id, proprietario_nome, proprietario_telefone, proprietario_email, observacoes)
    values (org.id, v_origem, v_corretor, v_nome, nullif(v_tel, ''), nullif(v_email, ''), nullif(v_msg, ''))
    returning id into v_id;
    insert into public.captacao_eventos (organizacao_id, captacao_id, tipo, descricao, usuario_id)
    values (org.id, v_id, 'entrada', 'Chegou pelo formulário (' || v_origem || ')', null);
    return jsonb_build_object('id', v_id, 'duplicado', false, 'captacao', true);
  end if;

  select l.id into v_existente
    from public.leads l
   where l.organizacao_id = org.id
     and l.status not in ('ganho','perdido')
     and ((v_email <> '' and lower(l.email) = v_email)
       or (length(v_dig) >= 8 and right(regexp_replace(coalesce(l.telefone, ''), '\D', '', 'g'), 9) = v_dig))
   limit 1;

  if p->>'imovel' is not null then
    select id into v_imovel from public.imoveis where organizacao_id = org.id and lower(codigo) = lower(p->>'imovel') limit 1;
  end if;

  if v_existente is not null then
    insert into public.lead_eventos (organizacao_id, lead_id, tipo, descricao, usuario_id)
    values (org.id, v_existente, 'mensagem', 'Novo contato (' || v_origem || ')' || coalesce(': ' || nullif(v_msg, ''), ''), null);
    update public.leads set ultimo_contato = now() where id = v_existente;
    if v_imovel is not null then
      insert into public.lead_imoveis (organizacao_id, lead_id, imovel_id) values (org.id, v_existente, v_imovel) on conflict do nothing;
    end if;
    return jsonb_build_object('id', v_existente, 'duplicado', true);
  end if;

  insert into public.leads (organizacao_id, nome, telefone, email, origem, funil, interesse, observacoes, corretor_id, atribuido_em, ultimo_contato)
  values (org.id, v_nome, nullif(v_tel, ''), nullif(v_email, ''), v_origem, v_funil,
          case when v_funil = 'venda' then 'compra' else 'locacao' end, nullif(v_msg, ''),
          v_corretor, case when v_corretor is not null then now() end, now())
  returning id into v_id;
  insert into public.lead_eventos (organizacao_id, lead_id, tipo, descricao, usuario_id)
  values (org.id, v_id, 'entrada', 'Chegou pelo formulário (' || v_origem || ')', null);
  if v_imovel is not null then
    insert into public.lead_imoveis (organizacao_id, lead_id, imovel_id) values (org.id, v_id, v_imovel);
  end if;
  return jsonb_build_object('id', v_id, 'duplicado', false);
end;
$$;
revoke execute on function public.receber_lead(uuid, jsonb) from public;
grant execute on function public.receber_lead(uuid, jsonb) to anon, authenticated;
