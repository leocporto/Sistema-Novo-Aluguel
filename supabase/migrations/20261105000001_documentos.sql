-- =============================================================================
-- Gestão de contratos e documentos (nos dois modos; modelos de venda,
-- administração, intermediação e exclusividade só aparecem na imobiliária):
-- modelos personalizáveis com variáveis, documentos gerados com os dados do
-- sistema, revisão/aprovação, versões, signatários e testemunhas, assinatura
-- eletrônica por link, vencimentos, documentos restritos e trilha de auditoria.
-- =============================================================================

create table if not exists public.documento_modelos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  nome text not null,
  tipo text not null default 'outro'
    check (tipo in ('locacao','venda','administracao','intermediacao','exclusividade','proposta','autorizacao','aditivo','vistoria','recibo','notificacao','outro')),
  conteudo text not null default '',
  ativo boolean not null default true,
  padrao_sistema text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.documentos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  numero bigint generated by default as identity,
  titulo text not null,
  tipo text not null default 'outro',
  modelo_id uuid references public.documento_modelos(id) on delete set null,
  imovel_id uuid references public.imoveis(id) on delete set null,
  pessoa_id uuid references public.pessoas(id) on delete set null,
  contrato_id uuid references public.contratos(id) on delete set null,
  venda_id uuid references public.vendas(id) on delete set null,
  captacao_id uuid references public.captacoes(id) on delete set null,
  status text not null default 'rascunho'
    check (status in ('rascunho','em_revisao','aprovado','aguardando_assinatura','assinado','recusado','cancelado','arquivo')),
  conteudo text,
  versao int not null default 1,
  arquivo_path text,
  arquivo_nome text,
  validade date,
  alerta_dias int not null default 30,
  restrito boolean not null default false,
  checklist jsonb not null default '{}'::jsonb,
  revisor_obs text,
  aprovado_em timestamptz,
  aprovado_por uuid,
  assinado_em timestamptz,
  hash_final text,
  criado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists documentos_busca_idx on public.documentos (organizacao_id, status);
create index if not exists documentos_imovel_idx on public.documentos (imovel_id);
create index if not exists documentos_pessoa_idx on public.documentos (pessoa_id);
create index if not exists documentos_validade_idx on public.documentos (organizacao_id, validade);

create table if not exists public.documento_versoes (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  documento_id uuid not null references public.documentos(id) on delete cascade,
  versao int not null,
  conteudo text,
  observacao text,
  criado_por uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists documento_versoes_idx on public.documento_versoes (documento_id, versao desc);

create table if not exists public.documento_signatarios (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  documento_id uuid not null references public.documentos(id) on delete cascade,
  pessoa_id uuid references public.pessoas(id) on delete set null,
  nome text not null,
  email text,
  telefone text,
  cpf text,
  papel text not null default 'parte'
    check (papel in ('locador','locatario','fiador','comprador','vendedor','proprietario','imobiliaria','testemunha','parte')),
  ordem int not null default 1,
  token uuid not null default gen_random_uuid(),
  visualizado_em timestamptz,
  assinado_em timestamptz,
  nome_assinado text,
  cpf_assinado text,
  ip text,
  user_agent text,
  hash_documento text,
  recusado_em timestamptz,
  motivo_recusa text
);
create unique index if not exists documento_signatarios_token_idx on public.documento_signatarios (token);
create index if not exists documento_signatarios_doc_idx on public.documento_signatarios (documento_id);

-- Trilha de auditoria: só acrescenta (ninguém altera nem apaga pelo app).
create table if not exists public.documento_eventos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  documento_id uuid not null references public.documentos(id) on delete cascade,
  tipo text not null,
  descricao text,
  usuario_id uuid default auth.uid(),
  ip text,
  data timestamptz not null default now()
);
create index if not exists documento_eventos_idx on public.documento_eventos (documento_id, data desc);

/** Quem pode ver documento restrito: administrador ou gestor da organização. */
create or replace function privado.pode_ver_restrito(p_org uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.membros m where m.organizacao_id = p_org and m.user_id = auth.uid() and m.papel in ('admin','gestor'))
$$;
revoke execute on function privado.pode_ver_restrito(uuid) from public, anon;
grant execute on function privado.pode_ver_restrito(uuid) to authenticated;

do $$
declare t text;
begin
  foreach t in array array['documento_modelos','documento_versoes','documento_signatarios','documento_eventos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create index if not exists %I on public.%I (organizacao_id)', t || '_org_idx', t);
    execute format('drop policy if exists %I on public.%I', t || '_org', t);
  end loop;
end $$;

create policy documento_modelos_org on public.documento_modelos for all to authenticated
  using (organizacao_id in (select privado.org_ids())) with check (organizacao_id in (select privado.org_ids()));
create policy documento_signatarios_org on public.documento_signatarios for all to authenticated
  using (organizacao_id in (select privado.org_ids())) with check (organizacao_id in (select privado.org_ids()));
-- Versões e eventos: ler e acrescentar; sem editar/apagar.
create policy documento_versoes_org on public.documento_versoes for select to authenticated using (organizacao_id in (select privado.org_ids()));
drop policy if exists documento_versoes_ins on public.documento_versoes;
create policy documento_versoes_ins on public.documento_versoes for insert to authenticated with check (organizacao_id in (select privado.org_ids()));
create policy documento_eventos_org on public.documento_eventos for select to authenticated using (organizacao_id in (select privado.org_ids()));
drop policy if exists documento_eventos_ins on public.documento_eventos;
create policy documento_eventos_ins on public.documento_eventos for insert to authenticated with check (organizacao_id in (select privado.org_ids()));

alter table public.documentos enable row level security;
create index if not exists documentos_org_idx on public.documentos (organizacao_id);
drop policy if exists documentos_org on public.documentos;
create policy documentos_org on public.documentos for all to authenticated
  using (organizacao_id in (select privado.org_ids()) and (not restrito or privado.pode_ver_restrito(organizacao_id)))
  with check (organizacao_id in (select privado.org_ids()));

-- Assinatura eletrônica por link (página pública /assinar/[token]) -----------
create or replace function public.info_assinatura(p_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.documento_signatarios%rowtype;
  d public.documentos%rowtype;
  v_org text;
begin
  select * into s from public.documento_signatarios where token = p_token;
  if not found then return null; end if;
  select * into d from public.documentos where id = s.documento_id;
  if d.status not in ('aguardando_assinatura','assinado','recusado') then return null; end if;
  select nome into v_org from public.organizacoes where id = d.organizacao_id;
  if s.visualizado_em is null then
    update public.documento_signatarios set visualizado_em = now() where id = s.id;
    insert into public.documento_eventos (organizacao_id, documento_id, tipo, descricao, usuario_id)
    values (d.organizacao_id, d.id, 'visualizado', s.nome || ' abriu o link de assinatura', null);
  end if;
  return jsonb_build_object(
    'titulo', d.titulo, 'conteudo', d.conteudo, 'status', d.status, 'versao', d.versao, 'organizacao', v_org,
    'hash', encode(sha256(convert_to(coalesce(d.conteudo, ''), 'UTF8')), 'hex'),
    'signatario', jsonb_build_object('nome', s.nome, 'papel', s.papel, 'cpf', s.cpf, 'assinado_em', s.assinado_em, 'recusado_em', s.recusado_em),
    'signatarios', (select coalesce(jsonb_agg(jsonb_build_object('nome', x.nome, 'papel', x.papel, 'assinado_em', x.assinado_em) order by x.ordem), '[]'::jsonb)
                      from public.documento_signatarios x where x.documento_id = d.id)
  );
end;
$$;
revoke execute on function public.info_assinatura(uuid) from public;
grant execute on function public.info_assinatura(uuid) to anon, authenticated;

create or replace function public.assinar_documento(p_token uuid, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.documento_signatarios%rowtype;
  d public.documentos%rowtype;
  v_nome text := left(btrim(coalesce(p->>'nome', '')), 160);
  v_cpf text := regexp_replace(coalesce(p->>'cpf', ''), '\D', '', 'g');
  v_hash text;
  v_faltam int;
begin
  select * into s from public.documento_signatarios where token = p_token for update;
  if not found then raise exception 'Link de assinatura inválido.'; end if;
  select * into d from public.documentos where id = s.documento_id for update;
  if d.status <> 'aguardando_assinatura' then raise exception 'Este documento não está disponível para assinatura.'; end if;
  if s.assinado_em is not null then raise exception 'Você já assinou este documento.'; end if;
  if coalesce((p->>'aceite')::boolean, false) is not true then raise exception 'Marque que leu e concorda com o documento.'; end if;
  if length(v_nome) < 3 then raise exception 'Digite seu nome completo.'; end if;
  if length(v_cpf) not in (11, 14) then raise exception 'Informe um CPF ou CNPJ válido.'; end if;
  if s.cpf is not null and regexp_replace(s.cpf, '\D', '', 'g') <> '' and regexp_replace(s.cpf, '\D', '', 'g') <> v_cpf then
    raise exception 'O CPF/CNPJ não confere com o cadastrado para este signatário.';
  end if;
  v_hash := encode(sha256(convert_to(coalesce(d.conteudo, ''), 'UTF8')), 'hex');
  update public.documento_signatarios
     set assinado_em = now(), nome_assinado = v_nome, cpf_assinado = v_cpf,
         ip = left(p->>'ip', 64), user_agent = left(p->>'ua', 300), hash_documento = v_hash
   where id = s.id;
  insert into public.documento_eventos (organizacao_id, documento_id, tipo, descricao, usuario_id, ip)
  values (d.organizacao_id, d.id, 'assinado', v_nome || ' (' || s.papel || ') assinou eletronicamente · hash ' || left(v_hash, 16), null, left(p->>'ip', 64));
  select count(*) into v_faltam from public.documento_signatarios where documento_id = d.id and assinado_em is null;
  if v_faltam = 0 then
    update public.documentos set status = 'assinado', assinado_em = now(), hash_final = v_hash where id = d.id;
    insert into public.documento_eventos (organizacao_id, documento_id, tipo, descricao, usuario_id)
    values (d.organizacao_id, d.id, 'concluido', 'Todos assinaram — documento concluído', null);
  end if;
  return jsonb_build_object('ok', true, 'concluido', v_faltam = 0);
end;
$$;
revoke execute on function public.assinar_documento(uuid, jsonb) from public;
grant execute on function public.assinar_documento(uuid, jsonb) to anon, authenticated;

create or replace function public.recusar_assinatura(p_token uuid, p_motivo text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.documento_signatarios%rowtype;
  d public.documentos%rowtype;
begin
  select * into s from public.documento_signatarios where token = p_token for update;
  if not found then raise exception 'Link de assinatura inválido.'; end if;
  select * into d from public.documentos where id = s.documento_id for update;
  if d.status <> 'aguardando_assinatura' or s.assinado_em is not null then raise exception 'Não é possível recusar agora.'; end if;
  update public.documento_signatarios set recusado_em = now(), motivo_recusa = left(coalesce(p_motivo, ''), 1000) where id = s.id;
  update public.documentos set status = 'recusado' where id = d.id;
  insert into public.documento_eventos (organizacao_id, documento_id, tipo, descricao, usuario_id)
  values (d.organizacao_id, d.id, 'recusado', s.nome || ' recusou: ' || coalesce(nullif(btrim(p_motivo), ''), 'sem motivo'), null);
end;
$$;
revoke execute on function public.recusar_assinatura(uuid, text) from public;
grant execute on function public.recusar_assinatura(uuid, text) to anon, authenticated;

-- Storage: bucket privado "documentos" (arquivos enviados) -------------------
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('documentos', 'documentos', false, 20971520,
            array['image/jpeg','image/png','image/webp','image/heic','application/pdf',
                  'application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document'])
    on conflict (id) do update
      set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
    execute 'drop policy if exists documentos_ler on storage.objects';
    execute 'drop policy if exists documentos_gravar on storage.objects';
    execute 'drop policy if exists documentos_apagar on storage.objects';
    execute $p$create policy documentos_ler on storage.objects for select to authenticated
      using (bucket_id = 'documentos' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy documentos_gravar on storage.objects for insert to authenticated
      with check (bucket_id = 'documentos' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy documentos_apagar on storage.objects for delete to authenticated
      using (bucket_id = 'documentos' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
  end if;
end $$;
