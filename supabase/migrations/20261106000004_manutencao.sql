  if v_partes[1] !~ v_uuid or v_partes[2] !~ v_uuid or v_partes[3] !~ v_uuid then return false; end if;
  return exists (
    select 1 from public.chamados
     where id = v_partes[2]::uuid and organizacao_id = v_partes[1]::uuid and upload_token = v_partes[3]::uuid
       and origem = 'link' and status in ('aberto','em_analise','aguardando_aprovacao','aprovado','agendado')
       and created_at > now() - interval '7 days');
end;
$$;
