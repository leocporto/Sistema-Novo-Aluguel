create or replace function public.responder_aprovacao_chamado(p_token uuid, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  ch public.chamados%rowtype;
  v_modo text;
  v_nome text := left(btrim(coalesce(p->>'nome', '')), 160);
  v_aprovar boolean := coalesce((p->>'aprovar')::boolean, false);
begin
  select * into ch from public.chamados where aprovacao_token = p_token for update;
  if not found then raise exception 'Link de aprovação inválido.'; end if;
  select modo into v_modo from public.organizacoes where id = ch.organizacao_id;
  if v_modo = 'pessoal' then raise exception 'Link de aprovação inválido.'; end if;
  if ch.aprovacao_status <> 'pendente' or ch.status <> 'aguardando_aprovacao' then
    raise exception 'Este orçamento não está mais aguardando a sua resposta.';
  end if;
  if length(v_nome) < 3 then raise exception 'Digite seu nome completo.'; end if;
  perform privado.aplicar_resposta_aprovacao(ch.id, v_aprovar, v_nome, left(nullif(btrim(p->>'obs'), ''), 1000), 'link', left(p->>'ip', 64));
  return jsonb_build_object('ok', true, 'aprovado', v_aprovar);
end;
$$;
revoke execute on function public.responder_aprovacao_chamado(uuid, jsonb) from public;
grant execute on function public.responder_aprovacao_chamado(uuid, jsonb) to anon, authenticated;

/** Resposta do proprietário registrada pela equipe (telefone, e-mail, pessoalmente). Só imobiliária. */
create or replace function public.registrar_aprovacao_chamado(p_chamado uuid, p jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  ch public.chamados%rowtype;
  v_nome text := left(btrim(coalesce(p->>'nome', '')), 160);
begin
  select * into ch from public.chamados where id = p_chamado;
  if not found then raise exception 'Chamado não encontrado.'; end if;
  if (select modo from public.organizacoes where id = ch.organizacao_id) = 'pessoal' then
    raise exception 'No modo pessoal não há aprovação de proprietário.';
  end if;
  if length(v_nome) < 2 then raise exception 'Informe quem respondeu.'; end if;
  perform privado.aplicar_resposta_aprovacao(ch.id, coalesce((p->>'aprovar')::boolean, false), v_nome,
                                             left(nullif(btrim(p->>'obs'), ''), 1000), 'manual', null);
end;
$$;
revoke execute on function public.registrar_aprovacao_chamado(uuid, jsonb) from public, anon;
grant execute on function public.registrar_aprovacao_chamado(uuid, jsonb) to authenticated;

-- Storage: bucket privado "manutencao" (fotos/vídeos dos chamados) ----------------
-- Equipe: pasta da organização. Locatário (anônimo, pelo link): só a pasta
-- <org>/<chamado>/<upload_token>/ do chamado que ele acabou de abrir.
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('manutencao', 'manutencao', false, 52428800,
            array['image/jpeg','image/png','image/webp','image/heic','video/mp4','video/quicktime','video/webm','application/pdf'])
    on conflict (id) do update
      set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
    if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'manutencao_ler') then
      execute $p$create policy manutencao_ler on storage.objects for select to authenticated
        using (bucket_id = 'manutencao' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'manutencao_gravar') then
      execute $p$create policy manutencao_gravar on storage.objects for insert to authenticated
        with check (bucket_id = 'manutencao' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'manutencao_apagar') then
      execute $p$create policy manutencao_apagar on storage.objects for delete to authenticated
        using (bucket_id = 'manutencao' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'manutencao_enviar_link') then
      execute $p$create policy manutencao_enviar_link on storage.objects for insert to anon
        with check (bucket_id = 'manutencao' and public.chamado_pode_enviar(name))$p$;
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'storage' and tablename = 'objects' and policyname = 'manutencao_ler_link') then
      execute $p$create policy manutencao_ler_link on storage.objects for select to anon
        using (bucket_id = 'manutencao' and public.chamado_pode_enviar(name))$p$;
    end if;
  end if;
end $$;

-- =============================================================================
-- Juntar cadastros repetidos (Pessoas): chamados e orçamentos vão para o
-- cadastro que fica (sem isso, o "on delete set null" apagaria o prestador e o
-- solicitante dos chamados, perdendo histórico e avaliação do prestador).
-- public.juntar_pessoas é recriada A PARTIR DO CORPO QUE ESTÁ NO BANCO, só
-- acrescentando a chamada antes do "delete from public.pessoas where id = b.id;"
-- (mesmo padrão da análise cadastral). Idempotente e sem DROP.
-- =============================================================================
create or replace function privado.manutencao_juntar_pessoas(p_manter uuid, p_remover uuid)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  update public.chamados set prestador_id = p_manter where prestador_id = p_remover;
  update public.chamados set solicitante_pessoa_id = p_manter where solicitante_pessoa_id = p_remover;
  update public.chamado_orcamentos set prestador_id = p_manter where prestador_id = p_remover;
end;
$$;
revoke execute on function privado.manutencao_juntar_pessoas(uuid, uuid) from public, anon;
grant execute on function privado.manutencao_juntar_pessoas(uuid, uuid) to authenticated;

do $$
declare
  v_def text;
  v_novo text;
begin
  if to_regprocedure('public.juntar_pessoas(uuid, uuid)') is null then
    raise warning 'public.juntar_pessoas não existe: chamados não entram no "juntar repetidos".';
    return;
  end if;
  v_def := pg_get_functiondef('public.juntar_pessoas(uuid, uuid)'::regprocedure);
  if v_def ilike '%privado.manutencao_juntar_pessoas%' then
    return;
  end if;
  v_novo := regexp_replace(v_def,
    '(\n[ \t]*)(delete[ \t]+from[ \t]+public\.pessoas[ \t]+where[ \t]+id[ \t]*=[ \t]*b\.id[ \t]*;)',
    '\1perform privado.manutencao_juntar_pessoas(a.id, b.id);\1\2', 'i');
  if v_novo = v_def then
    raise warning 'Não achei o "delete from public.pessoas where id = b.id;" em public.juntar_pessoas: inclua à mão a chamada a privado.manutencao_juntar_pessoas(a.id, b.id).';
    return;
  end if;
  execute v_novo;
end $$;
