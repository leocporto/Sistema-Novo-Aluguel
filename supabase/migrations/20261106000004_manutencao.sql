-- =============================================================================
-- Manutenção e chamados (nos dois modos).
-- - chamado ligado ao imóvel e (opcional) ao contrato, com categoria, urgência
--   e prazo de atendimento, fotos e vídeos (bucket privado "manutencao");
-- - abertura pelo locatário por link público (um link por contrato);
-- - responsabilidade financeira (locatário / proprietário / imobiliária /
--   dividido), aprovação do proprietário por link público (só imobiliária);
-- - orçamentos de vários prestadores, escolha, agendamento (agenda), ordem de
--   serviço, aprovação da conclusão, garantia e avaliação do prestador;
-- - ao concluir, lançamentos automáticos no Financeiro (sempre em aberto: a
--   baixa segue o gatilho de aprovação de pagamentos).
-- Sem DROP: funções/gatilhos com "create or replace" e policies criadas só se
-- ainda não existirem.
-- =============================================================================

create table if not exists public.chamados (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  numero bigint generated by default as identity,
  imovel_id uuid not null references public.imoveis(id) on delete cascade,
  contrato_id uuid references public.contratos(id) on delete set null,
  origem text not null default 'interno' check (origem in ('interno','link')),
  aberto_por text not null default 'equipe' check (aberto_por in ('locatario','proprietario','equipe','outro')),
  solicitante_pessoa_id uuid references public.pessoas(id) on delete set null,
  solicitante_nome text,
  solicitante_telefone text,
  categoria text not null default 'outros'
    check (categoria in ('hidraulica','eletrica','telhado','eletrodomestico','pintura','chaveiro','outros')),
  urgencia text not null default 'media' check (urgencia in ('baixa','media','alta','emergencia')),
  prazo_atendimento timestamptz,
  titulo text not null,
  descricao text,
  local text,
  status text not null default 'aberto'
    check (status in ('aberto','em_analise','aguardando_aprovacao','aprovado','agendado','em_execucao','concluido','avaliado','recusado','cancelado')),
  motivo text,
  -- Quem paga a conta (percentuais somam 100 quando definido)
  responsabilidade text check (responsabilidade in ('locatario','proprietario','imobiliaria','dividido')),
  pct_locatario numeric(6,3) not null default 0 check (pct_locatario between 0 and 100),
  pct_proprietario numeric(6,3) not null default 0 check (pct_proprietario between 0 and 100),
  pct_imobiliaria numeric(6,3) not null default 0 check (pct_imobiliaria between 0 and 100),
  -- O responsável paga direto ao prestador (o sistema não lança conta a pagar)
  pago_direto boolean not null default false,
  prestador_id uuid references public.pessoas(id) on delete set null,
  orcamento_id uuid,
  valor_aprovado numeric(14,2) check (valor_aprovado is null or valor_aprovado >= 0),
  -- Aprovação do proprietário (só imobiliária)
  aprovacao_status text not null default 'nao_precisa' check (aprovacao_status in ('nao_precisa','pendente','aprovado','recusado')),
  aprovacao_token uuid not null default gen_random_uuid(),
  aprovacao_em timestamptz,
  aprovacao_nome text,
  aprovacao_obs text,
  aprovacao_canal text check (aprovacao_canal is null or aprovacao_canal in ('link','manual')),
  aprovacao_ip text,
  -- Execução
  agendado_para timestamptz,
  duracao_min int not null default 120 check (duracao_min between 15 and 1440),
  visita_id uuid references public.visitas(id) on delete set null,
  iniciado_em timestamptz,
  locatario_confirmou_em timestamptz,
  locatario_comentario text,
  -- Conclusão
  concluido_em date,
  valor_final numeric(14,2) check (valor_final is null or valor_final >= 0),
  conclusao_aprovada_em timestamptz,
  conclusao_aprovada_por text,
  conclusao_obs text,
  garantia_dias int check (garantia_dias is null or garantia_dias between 0 and 3650),
  garantia_ate date,
  chamado_origem_id uuid references public.chamados(id) on delete set null,
  cobranca_locatario text check (cobranca_locatario is null or cobranca_locatario in ('fatura','receber')),
  fatura_item_id uuid references public.fatura_itens(id) on delete set null,
  -- Avaliação do prestador
  avaliacao_nota int check (avaliacao_nota is null or avaliacao_nota between 1 and 5),
  avaliacao_comentario text,
  avaliado_em timestamptz,
  -- Envio de fotos pelo locatário (pasta <org>/<chamado>/<upload_token>/ no bucket)
  upload_token uuid not null default gen_random_uuid(),
  criado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
