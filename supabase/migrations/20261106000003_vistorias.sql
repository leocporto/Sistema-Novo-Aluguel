do $$
declare t text;
begin
  foreach t in array array['vistorias','vistoria_ambientes','vistoria_itens','vistoria_medidores','vistoria_midias','vistoria_pendencias','vistoria_orcamentos','vistoria_contestacoes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create index if not exists %I on public.%I (organizacao_id)', t || '_org_idx', t);
    execute format('drop policy if exists %I on public.%I', t || '_org', t);
    execute format($p$create policy %I on public.%I for all to authenticated
      using (organizacao_id in (select privado.org_ids()))
      with check (organizacao_id in (select privado.org_ids()))$p$, t || '_org', t);
  end loop;
end $$;
alter table public.vistoria_eventos enable row level security;
create index if not exists vistoria_eventos_org_idx on public.vistoria_eventos (organizacao_id);
drop policy if exists vistoria_eventos_ler on public.vistoria_eventos;
create policy vistoria_eventos_ler on public.vistoria_eventos for select to authenticated
  using (organizacao_id in (select privado.org_ids()));
drop policy if exists vistoria_eventos_ins on public.vistoria_eventos;
create policy vistoria_eventos_ins on public.vistoria_eventos for insert to authenticated
  with check (organizacao_id in (select privado.org_ids()));

/** O item herda vistoria e organização do ambiente (não dá para pendurar item em ambiente de outra conta). */
create or replace function privado.vistoria_item_herdar()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_vistoria uuid;
  v_org uuid;
begin
  select vistoria_id, organizacao_id into v_vistoria, v_org from public.vistoria_ambientes where id = new.ambiente_id;
  if v_vistoria is null then raise exception 'Ambiente da vistoria não encontrado.'; end if;
  new.vistoria_id := v_vistoria;
  new.organizacao_id := v_org;
  return new;
end;
$$;
drop trigger if exists vistoria_itens_herdar_trg on public.vistoria_itens;
create trigger vistoria_itens_herdar_trg before insert or update of ambiente_id on public.vistoria_itens
  for each row execute function privado.vistoria_item_herdar();

/**
 * Salva de uma vez o estado e a observação de vários itens (formulário do
 * ambiente e sincronização do app de campo). Só mexe no que mudou.
 * p_itens: [{ id, estado, observacao }]
 */
create or replace function public.salvar_itens_vistoria(p_itens jsonb)
returns int
language plpgsql
security invoker
set search_path = public
as $$
declare
  n int;
begin
  update public.vistoria_itens i
     set estado = nullif(x.estado, ''),
         observacao = nullif(btrim(coalesce(x.observacao, '')), ''),
         updated_at = now()
    from jsonb_to_recordset(coalesce(p_itens, '[]'::jsonb)) as x(id uuid, estado text, observacao text)
   where i.id = x.id
     and (i.estado is distinct from nullif(x.estado, '')
          or i.observacao is distinct from nullif(btrim(coalesce(x.observacao, '')), ''));
  get diagnostics n = row_count;
  return n;
end;
$$;
revoke execute on function public.salvar_itens_vistoria(jsonb) from public, anon;
grant execute on function public.salvar_itens_vistoria(jsonb) to authenticated;

/**
 * Leva os reparos da vistoria de saída para o acerto da desocupação do
 * contrato: soma as pendências de responsabilidade do locatário (orçamento
 * aprovado ou, sem ele, o valor estimado), grava em reparos e registra o
 * resultado da vistoria. Devolve o total.
 */
create or replace function public.aplicar_vistoria_no_acerto(p_vistoria uuid)
returns numeric
language plpgsql
security invoker
set search_path = public
as $$
declare
  v public.vistorias%rowtype;
  d public.contrato_desocupacoes%rowtype;
  v_total numeric(14,2);
  v_obs text;
  v_qtd int;
begin
  select * into v from public.vistorias where id = p_vistoria;
  if not found then raise exception 'Vistoria não encontrada.'; end if;
  if v.tipo <> 'saida' then raise exception 'Só a vistoria de saída vai para o acerto do contrato.'; end if;
  if v.desocupacao_id is not null then
    select * into d from public.contrato_desocupacoes where id = v.desocupacao_id for update;
  elsif v.contrato_id is not null then
    select * into d from public.contrato_desocupacoes where contrato_id = v.contrato_id for update;
  end if;
  if d.id is null then raise exception 'O contrato não tem desocupação em andamento. Inicie a desocupação no contrato (Encerramento).'; end if;
  if d.status = 'concluida' then raise exception 'A desocupação deste contrato já foi concluída.'; end if;

  select coalesce(sum(coalesce((select o.valor from public.vistoria_orcamentos o where o.pendencia_id = p.id and o.aprovado limit 1), p.valor_estimado, 0)), 0),
         string_agg(p.descricao || coalesce(' (' || a.nome || ')', ''), '; ' order by p.created_at),
         count(*)
    into v_total, v_obs, v_qtd
    from public.vistoria_pendencias p
    left join public.vistoria_ambientes a on a.id = p.ambiente_id
   where p.vistoria_id = v.id and p.responsavel = 'locatario' and p.status <> 'cancelada';

  update public.contrato_desocupacoes
     set reparos = v_total,
         vistoria_data = v.data,
         vistoria_resultado = case when v_qtd > 0 then 'com_reparos' else 'ok' end,
         vistoria_obs = left('Vistoria de saída nº ' || v.numero || ': ' || coalesce(v_obs, 'imóvel em ordem.'), 2000),
         status = case when status = 'aviso' then 'vistoria' else status end
   where id = d.id;
  update public.vistorias set desocupacao_id = d.id, updated_at = now() where id = v.id;
  insert into public.vistoria_eventos (organizacao_id, vistoria_id, tipo, descricao)
  values (v.organizacao_id, v.id, 'acerto', 'Reparos do locatário (R$ ' || replace(to_char(v_total, 'FM999999999990.00'), '.', ',') || ') levados para o acerto de saída');
  return v_total;
end;
$$;
revoke execute on function public.aplicar_vistoria_no_acerto(uuid) from public, anon;
grant execute on function public.aplicar_vistoria_no_acerto(uuid) to authenticated;

/** Laudo assinado por todos (página /assinar) → a vistoria fica "assinada". */
create or replace function privado.vistoria_documento_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'assinado' and old.status is distinct from 'assinado' then
    update public.vistorias
       set assinada_em = now(), updated_at = now(),
           status = case when status = 'concluida' then 'assinada' else status end
     where documento_id = new.id and status in ('concluida','contestada');
    insert into public.vistoria_eventos (organizacao_id, vistoria_id, tipo, descricao, usuario_id)
    select organizacao_id, id, 'assinada', 'Laudo assinado eletronicamente por todos os envolvidos', auth.uid()
      from public.vistorias where documento_id = new.id;
  elsif new.status = 'recusado' and old.status is distinct from 'recusado' then
    insert into public.vistoria_eventos (organizacao_id, vistoria_id, tipo, descricao, usuario_id)
    select organizacao_id, id, 'recusa', 'Um dos envolvidos recusou assinar o laudo', auth.uid()
      from public.vistorias where documento_id = new.id;
  end if;
  return new;
end;
$$;
drop trigger if exists documentos_vistoria_trg on public.documentos;
create trigger documentos_vistoria_trg after update of status on public.documentos
  for each row execute function privado.vistoria_documento_status();

-- Contestação pública (/contestar/[token]) -----------------------------------
/** Dados da vistoria para o locatário conferir e contestar (só com o token certo). */
create or replace function public.info_contestacao_vistoria(p_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.vistorias%rowtype;
  v_org text;
  v_end text;
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  select * into v from public.vistorias where contestacao_token = p_token;
  if not found or v.status not in ('concluida','assinada','contestada') then return null; end if;
  select nome into v_org from public.organizacoes where id = v.organizacao_id;
  select concat_ws(', ', i.logradouro, i.numero, i.complemento, i.bairro, i.cidade) into v_end from public.imoveis i where i.id = v.imovel_id;
  return jsonb_build_object(
    'organizacao', v_org,
    'organizacao_id', v.organizacao_id,
    'numero', v.numero,
    'tipo', v.tipo,
    'data', v.data,
    'status', v.status,
    'prazo', v.contestacao_ate,
    'aberta', (v.contestacao_ate is null or v_hoje <= v.contestacao_ate),
    'imovel', v_end,
    'conclusao', v.conclusao,
    'ambientes', (
      select coalesce(jsonb_agg(jsonb_build_object(
               'nome', a.nome,
               'observacoes', a.observacoes,
               'itens', (select coalesce(jsonb_agg(jsonb_build_object('id', it.id, 'nome', it.nome, 'estado', it.estado, 'observacao', it.observacao) order by it.ordem, it.nome), '[]'::jsonb)
                           from public.vistoria_itens it where it.ambiente_id = a.id)
             ) order by a.ordem, a.created_at), '[]'::jsonb)
        from public.vistoria_ambientes a where a.vistoria_id = v.id),
    'medidores', (
      select coalesce(jsonb_agg(jsonb_build_object('tipo', m.tipo, 'numero', m.numero, 'leitura', m.leitura) order by m.tipo, m.created_at), '[]'::jsonb)
        from public.vistoria_medidores m where m.vistoria_id = v.id),
    'pendencias', (
      select coalesce(jsonb_agg(jsonb_build_object('descricao', p.descricao, 'responsavel', p.responsavel, 'status', p.status) order by p.created_at), '[]'::jsonb)
        from public.vistoria_pendencias p where p.vistoria_id = v.id and p.status <> 'cancelada'),
    'contestacoes', (
      select coalesce(jsonb_agg(jsonb_build_object('nome', c.nome, 'texto', c.texto, 'criada_em', c.created_at, 'status', c.status,
                                                   'decisao', c.decisao, 'resposta', c.resposta, 'respondida_em', c.respondida_em) order by c.created_at), '[]'::jsonb)
        from public.vistoria_contestacoes c where c.vistoria_id = v.id)
  );
end;
$$;
revoke execute on function public.info_contestacao_vistoria(uuid) from public;
grant execute on function public.info_contestacao_vistoria(uuid) to anon, authenticated;

/**
 * O locatário registra a contestação pelo link (dentro do prazo).
 * p: { nome, contato, texto, itens: [{ item_id, texto }], fotos: [caminhos], ip, ua }
 * As fotos precisam estar na pasta <organização>/contestacoes/<token>/ do bucket.
 */
create or replace function public.contestar_vistoria(p_token uuid, p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.vistorias%rowtype;
  v_nome text := left(btrim(coalesce(p->>'nome', '')), 160);
  v_texto text := left(btrim(coalesce(p->>'texto', '')), 5000);
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  v_prefixo text;
  v_fotos text[];
  v_itens jsonb;
  v_qtd int;
  v_id uuid;
begin
  select * into v from public.vistorias where contestacao_token = p_token for update;
  if not found or v.status not in ('concluida','assinada','contestada') then raise exception 'Link de contestação inválido.'; end if;
  if v.contestacao_ate is not null and v_hoje > v.contestacao_ate then
    raise exception 'O prazo para contestar esta vistoria terminou em %.', to_char(v.contestacao_ate, 'DD/MM/YYYY');
  end if;
  if length(v_nome) < 3 then raise exception 'Digite seu nome completo.'; end if;
  if length(v_texto) < 10 then raise exception 'Explique com o que você não concorda (pelo menos uma frase).'; end if;
  select count(*) into v_qtd from public.vistoria_contestacoes where vistoria_id = v.id and origem = 'link';
  if v_qtd >= 10 then raise exception 'Este link já recebeu o máximo de contestações. Fale com quem enviou a vistoria.'; end if;

  v_prefixo := v.organizacao_id::text || '/contestacoes/' || v.contestacao_token::text || '/';
  select coalesce(array_agg(f), '{}') into v_fotos
    from jsonb_array_elements_text(case when jsonb_typeof(p->'fotos') = 'array' then p->'fotos' else '[]'::jsonb end) f;
  if coalesce(array_length(v_fotos, 1), 0) > 20 then raise exception 'Envie no máximo 20 fotos.'; end if;
  if exists (select 1 from unnest(v_fotos) f where left(f, length(v_prefixo)) <> v_prefixo or f like '%..%') then
    raise exception 'Foto inválida.';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('item_id', it.id, 'item', a.nome || ' · ' || it.nome, 'texto', left(coalesce(x->>'texto', ''), 1000))), '[]'::jsonb)
    into v_itens
    from jsonb_array_elements(case when jsonb_typeof(p->'itens') = 'array' then p->'itens' else '[]'::jsonb end) x
    join public.vistoria_itens it on it.id::text = x->>'item_id' and it.vistoria_id = v.id
    join public.vistoria_ambientes a on a.id = it.ambiente_id;

  insert into public.vistoria_contestacoes (organizacao_id, vistoria_id, nome, contato, texto, itens, fotos, origem, ip, user_agent)
  values (v.organizacao_id, v.id, v_nome, left(nullif(btrim(coalesce(p->>'contato', '')), ''), 160), v_texto, v_itens, v_fotos, 'link',
          left(p->>'ip', 64), left(p->>'ua', 300))
  returning id into v_id;
  update public.vistorias set status = 'contestada', updated_at = now() where id = v.id;
  insert into public.vistoria_eventos (organizacao_id, vistoria_id, tipo, descricao, usuario_id)
  values (v.organizacao_id, v.id, 'contestada', v_nome || ' contestou a vistoria pelo link', null);
  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;
revoke execute on function public.contestar_vistoria(uuid, jsonb) from public;
grant execute on function public.contestar_vistoria(uuid, jsonb) to anon, authenticated;

/** A pasta de fotos da contestação está aberta? (usada pela política do Storage para o visitante) */
create or replace function public.vistoria_contestacao_aberta(p_org text, p_token text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if p_org is null or p_token is null
     or p_org !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     or p_token !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    return false;
  end if;
  return exists (
    select 1 from public.vistorias v
     where v.organizacao_id = p_org::uuid and v.contestacao_token = p_token::uuid
       and v.status in ('concluida','assinada','contestada')
       and (v.contestacao_ate is null or (now() at time zone 'America/Sao_Paulo')::date <= v.contestacao_ate));
end;
$$;
revoke execute on function public.vistoria_contestacao_aberta(text, text) from public;
grant execute on function public.vistoria_contestacao_aberta(text, text) to anon, authenticated;

-- Storage: bucket privado "vistorias" (fotos e vídeos) ---------------------------
-- Pasta: <organização>/<vistoria>/… ; contestação: <organização>/contestacoes/<token>/…
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('vistorias', 'vistorias', false, 52428800,
            array['image/jpeg','image/png','image/webp','image/heic','image/heif','video/mp4','video/quicktime','video/webm'])
    on conflict (id) do update
      set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
    execute 'drop policy if exists vistorias_ler on storage.objects';
    execute 'drop policy if exists vistorias_gravar on storage.objects';
    execute 'drop policy if exists vistorias_apagar on storage.objects';
    execute 'drop policy if exists vistorias_contestacao_anon on storage.objects';
    execute $p$create policy vistorias_ler on storage.objects for select to authenticated
      using (bucket_id = 'vistorias' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy vistorias_gravar on storage.objects for insert to authenticated
      with check (bucket_id = 'vistorias' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy vistorias_apagar on storage.objects for delete to authenticated
      using (bucket_id = 'vistorias' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    -- Visitante (locatário pelo link) só envia foto para a pasta da própria contestação, dentro do prazo.
    execute $p$create policy vistorias_contestacao_anon on storage.objects for insert to anon
      with check (bucket_id = 'vistorias' and (storage.foldername(name))[2] = 'contestacoes'
                  and public.vistoria_contestacao_aberta((storage.foldername(name))[1], (storage.foldername(name))[3]))$p$;
  end if;
end $$;
