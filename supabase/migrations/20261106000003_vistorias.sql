-- =============================================================================
-- Vistorias imobiliárias (nos dois modos; no pessoal o próprio dono faz a
-- vistoria, sem vistoriador da imobiliária):
-- - vistoria de entrada, saída e periódica (rascunho → em andamento →
--   concluída → assinada / contestada);
-- - checklist por ambiente com o estado de cada item (paredes, piso, teto,
--   portas, janelas, elétrica, hidráulica, pintura, móveis…);
-- - fotos e vídeos identificados (ambiente, item, legenda, data) no bucket
--   privado "vistorias";
-- - medidores de água, energia e gás;
-- - danos e pendências com responsável e orçamentos de reparo, que alimentam o
--   acerto de saída do contrato (contrato_desocupacoes.reparos);
-- - laudo para assinatura: reaproveita documentos + documento_signatarios e a
--   página pública /assinar/[token] (gatilho marca a vistoria como assinada);
-- - contestação pelo locatário por link público (/contestar/[token]) via RPC
--   security definer, com prazo, texto e fotos;
-- - histórico da vistoria (só acrescenta).
-- =============================================================================

create table if not exists public.vistorias (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  numero bigint generated by default as identity,
  tipo text not null default 'entrada' check (tipo in ('entrada','saida','periodica')),
  status text not null default 'rascunho' check (status in ('rascunho','em_andamento','concluida','assinada','contestada')),
  imovel_id uuid not null references public.imoveis(id) on delete cascade,
  contrato_id uuid references public.contratos(id) on delete set null,
  desocupacao_id uuid references public.contrato_desocupacoes(id) on delete set null,
  visita_id uuid references public.visitas(id) on delete set null,
  referencia_id uuid references public.vistorias(id) on delete set null,
  data date not null default current_date,
  responsavel_id uuid references public.pessoas(id) on delete set null,
  responsavel_nome text,
  acompanhante text,
  observacoes text,
  conclusao text,
  iniciada_em timestamptz,
  concluida_em timestamptz,
  assinada_em timestamptz,
  documento_id uuid references public.documentos(id) on delete set null,
  contestacao_token uuid not null default gen_random_uuid(),
  contestacao_dias int not null default 10 check (contestacao_dias between 0 and 90),
  contestacao_ate date,
  criado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists vistorias_token_idx on public.vistorias (contestacao_token);
create index if not exists vistorias_imovel_idx on public.vistorias (imovel_id, data desc);
create index if not exists vistorias_contrato_idx on public.vistorias (contrato_id);
create index if not exists vistorias_status_idx on public.vistorias (organizacao_id, status);
create index if not exists vistorias_documento_idx on public.vistorias (documento_id);

