-- =============================================================================
-- Gestão de vendas (modo imobiliária): processo da venda depois da proposta —
-- propostas e contrapropostas, reserva, aprovação do proprietário, sinal e
-- cronograma de pagamentos, financiamento, documentação e certidões, ITBI e
-- despesas, escritura e registro, divisão de comissão, posse e pós-venda.
-- =============================================================================

create table if not exists public.vendas (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  numero bigint generated by default as identity,
  imovel_id uuid references public.imoveis(id) on delete set null,
  comprador_id uuid references public.pessoas(id) on delete set null,
  comprador_nome text,
  comprador_telefone text,
  lead_id uuid references public.leads(id) on delete set null,
  corretor_id uuid references public.pessoas(id) on delete set null,
  status text not null default 'negociacao'
    check (status in ('proposta','negociacao','reservado','aprovado','documentacao','financiamento','escritura','registro','concluida','cancelada')),
  valor numeric(14,2) not null default 0 check (valor >= 0),
  forma_pagamento text not null default 'a_vista'
    check (forma_pagamento in ('a_vista','financiamento','consorcio','permuta','misto')),
  reserva_ate date,
  aprovado_proprietario_em date,
  -- Financiamento
  banco text,
  valor_financiado numeric(14,2),
  fin_status text not null default 'nao_se_aplica'
    check (fin_status in ('nao_se_aplica','simulacao','analise_credito','aprovado','avaliacao_banco','contrato_assinado','liberado','negado')),
  fin_observacoes text,
  -- Transferência
  itbi_aliquota numeric(6,3) not null default 2,
  itbi_valor numeric(14,2),
  itbi_pago_em date,
  cartorio text,
  escritura_data date,
  registro_data date,
  matricula text,
  -- Posse e pós-venda
  posse_data date,
  checklist_docs jsonb not null default '{}'::jsonb,
  checklist_posse jsonb not null default '{}'::jsonb,
  pos_venda_nota int check (pos_venda_nota is null or pos_venda_nota between 1 and 5),
  pos_venda_texto text,
  pos_venda_contato_em date,
  -- Comissão
  comissao_pct numeric(6,3) not null default 6 check (comissao_pct >= 0 and comissao_pct <= 100),
  comissao_valor numeric(14,2),
  lancamento_receber_id uuid,
  -- Resultado
  concluida_em date,
  motivo_cancelamento text,
  observacoes text,
  created_at timestamptz not null default now()
);
create index if not exists vendas_status_idx on public.vendas (organizacao_id, status);

-- Propostas e contrapropostas ligadas à venda
alter table public.propostas
  add column if not exists venda_id uuid references public.vendas(id) on delete cascade,
  add column if not exists proposta_pai_id uuid references public.propostas(id) on delete set null,
  add column if not exists autor text not null default 'comprador',
  add column if not exists validade date,
  add column if not exists condicoes text,
  add column if not exists sinal_valor numeric(14,2),
  add column if not exists forma_pagamento text,
  add column if not exists aprovada_proprietario_em date;
alter table public.propostas drop constraint if exists propostas_status_check;
alter table public.propostas add constraint propostas_status_check
  check (status in ('em_negociacao','contraproposta','aceita','recusada','cancelada'));
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'propostas_autor_check') then
    alter table public.propostas add constraint propostas_autor_check check (autor in ('comprador','proprietario'));
  end if;
end $$;
create index if not exists propostas_venda_idx on public.propostas (venda_id);

alter table public.lancamentos add column if not exists venda_id uuid references public.vendas(id) on delete set null;
create index if not exists lancamentos_venda_idx on public.lancamentos (venda_id);

create table if not exists public.venda_pagamentos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  venda_id uuid not null references public.vendas(id) on delete cascade,
  tipo text not null default 'parcela' check (tipo in ('sinal','entrada','parcela','financiamento','fgts','consorcio','permuta','outro')),
  descricao text,
  valor numeric(14,2) not null check (valor > 0),
  vencimento date,
  pago_em date,
  created_at timestamptz not null default now()
);

create table if not exists public.venda_despesas (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  venda_id uuid not null references public.vendas(id) on delete cascade,
  tipo text not null default 'outro' check (tipo in ('itbi','escritura','registro','certidoes','laudo','taxa_banco','outro')),
  descricao text,
  valor numeric(14,2) not null check (valor >= 0),
  responsavel text not null default 'comprador' check (responsavel in ('comprador','vendedor','imobiliaria')),
  vencimento date,
  pago_em date
);

create table if not exists public.venda_comissoes (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  venda_id uuid not null references public.vendas(id) on delete cascade,
  pessoa_id uuid references public.pessoas(id) on delete set null,
  papel text not null default 'vendedor' check (papel in ('captador','vendedor','parceiro','gerente','imobiliaria')),
  percentual numeric(6,3) not null check (percentual > 0 and percentual <= 100),
  lancamento_id uuid references public.lancamentos(id) on delete set null,
  check (papel = 'imobiliaria' or pessoa_id is not null)
);

create table if not exists public.venda_eventos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  venda_id uuid not null references public.vendas(id) on delete cascade,
  tipo text not null default 'nota',
  descricao text,
  data timestamptz not null default now(),
  usuario_id uuid default auth.uid()
);
create index if not exists venda_eventos_idx on public.venda_eventos (venda_id, data desc);

create table if not exists public.venda_arquivos (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null default privado.org_atual() references public.organizacoes(id) on delete cascade,
  venda_id uuid not null references public.vendas(id) on delete cascade,
  parte text not null default 'outro' check (parte in ('comprador','vendedor','imovel','contrato','outro')),
  categoria text not null,
  path text not null,
  nome text,
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['vendas','venda_pagamentos','venda_despesas','venda_comissoes','venda_eventos','venda_arquivos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create index if not exists %I on public.%I (organizacao_id)', t || '_org_idx', t);
    execute format('drop policy if exists %I on public.%I', t || '_org', t);
    execute format($p$create policy %I on public.%I for all to authenticated
      using (organizacao_id in (select privado.org_ids()))
      with check (organizacao_id in (select privado.org_ids()))$p$, t || '_org', t);
  end loop;
end $$;

-- O imóvel acompanha a venda: reservado durante o processo, disponível de novo
-- se voltar para negociação ou for cancelada (vendido só ao concluir).
create or replace function public.vendas_imovel()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.imovel_id is null or new.status = 'concluida' then return new; end if;
  if new.status in ('reservado','aprovado','documentacao','financiamento','escritura','registro') then
    update public.imoveis set status = 'reservado' where id = new.imovel_id and status = 'disponivel';
  elsif tg_op = 'UPDATE' and old.status in ('reservado','aprovado','documentacao','financiamento','escritura','registro') then
    update public.imoveis set status = 'disponivel' where id = new.imovel_id and status = 'reservado';
  end if;
  return new;
end;
$$;
drop trigger if exists vendas_imovel_trg on public.vendas;
create trigger vendas_imovel_trg after insert or update of status on public.vendas
  for each row execute function public.vendas_imovel();

-- Aceitar proposta: venda abre/atualiza o processo de venda (sem marcar
-- vendido ainda); locação continua igual (reserva + comissão).
create or replace function public.aceitar_proposta(p_id uuid)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  p public.propostas%rowtype;
  v_codigo text;
  v_comissao numeric(14,2);
  v_venda uuid;
  v_lead public.leads%rowtype;
begin
  select * into p from public.propostas where id = p_id for update;
  if not found then raise exception 'Proposta não encontrada.'; end if;
  if p.status not in ('em_negociacao','contraproposta') then raise exception 'Esta proposta não está mais em negociação.'; end if;

  update public.propostas set status = 'aceita', fechada_em = current_date where id = p.id;

  if p.tipo = 'venda' then
    v_venda := p.venda_id;
    if v_venda is null then
      if p.lead_id is not null then select * into v_lead from public.leads where id = p.lead_id; end if;
      insert into public.vendas (organizacao_id, imovel_id, lead_id, corretor_id, comprador_nome, comprador_telefone, valor, status, comissao_pct)
      values (p.organizacao_id, p.imovel_id, p.lead_id, p.corretor_id, v_lead.nome, v_lead.telefone, p.valor, 'aprovado', coalesce(p.comissao_pct, 6))
      returning id into v_venda;
      update public.propostas set venda_id = v_venda where id = p.id;
      if p.corretor_id is not null then
        insert into public.venda_comissoes (organizacao_id, venda_id, pessoa_id, papel, percentual)
        values (p.organizacao_id, v_venda, p.corretor_id, 'vendedor', 100);
      end if;
    else
      update public.vendas set valor = p.valor, status = case when status in ('proposta','negociacao') then 'aprovado' else status end
       where id = v_venda;
    end if;
    update public.vendas set aprovado_proprietario_em = coalesce(p.aprovada_proprietario_em, current_date),
                             forma_pagamento = coalesce(p.forma_pagamento, forma_pagamento)
     where id = v_venda;
    -- As outras propostas abertas dessa venda ficam recusadas.
    update public.propostas set status = 'recusada', fechada_em = current_date
     where venda_id = v_venda and id <> p.id and status in ('em_negociacao','contraproposta');
    insert into public.venda_eventos (organizacao_id, venda_id, tipo, descricao)
    values (p.organizacao_id, v_venda, 'proposta', 'Proposta de ' || to_char(p.valor, 'FM999G999G999D00') || ' aceita');
    if p.lead_id is not null then
      update public.leads set status = 'proposta' where id = p.lead_id and status in ('novo','em_atendimento','visita');
    end if;
    return;
  end if;

  -- Locação
  if p.lead_id is not null then
    update public.leads set status = 'ganho' where id = p.lead_id;
  end if;
  if p.imovel_id is not null then
    update public.imoveis set status = 'reservado' where id = p.imovel_id and status = 'disponivel';
    select codigo into v_codigo from public.imoveis where id = p.imovel_id;
  end if;
  if p.corretor_id is not null and coalesce(p.comissao_pct, 0) > 0 then
    v_comissao := round(p.valor * p.comissao_pct / 100, 2);
    insert into public.lancamentos (organizacao_id, tipo, descricao, categoria, valor, vencimento, status, pessoa_id, imovel_id, proposta_id)
    values (p.organizacao_id, 'pagar', 'Comissão de locação' || coalesce(' — ' || v_codigo, ''),
            'Comissões', v_comissao, current_date + 30, 'aberto', p.corretor_id, p.imovel_id, p.id);
  end if;
end;
$$;
revoke execute on function public.aceitar_proposta(uuid) from public, anon;
grant execute on function public.aceitar_proposta(uuid) to authenticated;

/**
 * Conclui a venda: imóvel vendido, lead ganho, comissão a receber (total) e
 * comissões a pagar (divisão entre corretores/parceiros). Não lança duas vezes.
 */
create or replace function public.concluir_venda(p_id uuid)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v public.vendas%rowtype;
  v_total numeric(14,2);
  v_codigo text;
  v_prop uuid;
  r record;
  v_lanc uuid;
begin
  select * into v from public.vendas where id = p_id for update;
  if not found then raise exception 'Venda não encontrada.'; end if;
  if v.status = 'concluida' then raise exception 'Esta venda já foi concluída.'; end if;
  if v.status = 'cancelada' then raise exception 'Esta venda foi cancelada.'; end if;
  if v.valor <= 0 then raise exception 'Informe o valor da venda.'; end if;

  v_total := coalesce(v.comissao_valor, round(v.valor * v.comissao_pct / 100, 2));
  select codigo into v_codigo from public.imoveis where id = v.imovel_id;
  select pessoa_id into v_prop from public.imovel_proprietarios where imovel_id = v.imovel_id order by percentual desc limit 1;

  if v_total > 0 and v.lancamento_receber_id is null then
    insert into public.lancamentos (organizacao_id, tipo, descricao, categoria, valor, vencimento, status, pessoa_id, imovel_id, venda_id)
    values (v.organizacao_id, 'receber', 'Comissão de venda' || coalesce(' — ' || v_codigo, ''), 'Comissões de venda',
            v_total, current_date, 'aberto', v_prop, v.imovel_id, v.id)
    returning id into v_lanc;
    update public.vendas set lancamento_receber_id = v_lanc where id = v.id;
  end if;

  for r in select c.*, p.nome from public.venda_comissoes c left join public.pessoas p on p.id = c.pessoa_id
            where c.venda_id = v.id and c.lancamento_id is null and c.papel <> 'imobiliaria' loop
    insert into public.lancamentos (organizacao_id, tipo, descricao, categoria, valor, vencimento, status, pessoa_id, imovel_id, venda_id)
    values (v.organizacao_id, 'pagar', 'Comissão de venda (' || r.papel || ')' || coalesce(' — ' || v_codigo, ''), 'Comissões',
            round(v_total * r.percentual / 100, 2), current_date + 30, 'aberto', r.pessoa_id, v.imovel_id, v.id)
    returning id into v_lanc;
    update public.venda_comissoes set lancamento_id = v_lanc where id = r.id;
  end loop;

  update public.vendas set status = 'concluida', concluida_em = current_date where id = v.id;
  if v.imovel_id is not null then
    update public.imoveis set status = 'vendido', vendido_em = current_date where id = v.imovel_id;
  end if;
  if v.lead_id is not null then
    update public.leads set status = 'ganho' where id = v.lead_id;
  end if;
  insert into public.venda_eventos (organizacao_id, venda_id, tipo, descricao)
  values (v.organizacao_id, v.id, 'conclusao', 'Venda concluída' || coalesce(' — ' || v_codigo, ''));
end;
$$;
revoke execute on function public.concluir_venda(uuid) from public, anon;
grant execute on function public.concluir_venda(uuid) to authenticated;

-- Storage: bucket privado "vendas" (documentos de comprador, vendedor e imóvel)
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('vendas', 'vendas', false, 10485760,
            array['image/jpeg','image/png','image/webp','image/heic','application/pdf'])
    on conflict (id) do update
      set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

    execute 'drop policy if exists vendas_ler on storage.objects';
    execute 'drop policy if exists vendas_gravar on storage.objects';
    execute 'drop policy if exists vendas_apagar on storage.objects';
    execute $p$create policy vendas_ler on storage.objects for select to authenticated
      using (bucket_id = 'vendas' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy vendas_gravar on storage.objects for insert to authenticated
      with check (bucket_id = 'vendas' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
    execute $p$create policy vendas_apagar on storage.objects for delete to authenticated
      using (bucket_id = 'vendas' and (storage.foldername(name))[1] in (select privado.org_ids()::text))$p$;
  end if;
end $$;
